def appendix_text():
    header("Appendix text and Figure 11 caption")

    d = DEC[(QWEN, DATASETS[0][0], "word_reversal")]
    show("Fig 11 caption", "Word Reversal 2024: verbatim, median CER, 4gF1, stub",
         "%.1f  %.3f  %.1f  %.1f" % (pct(d["recovered_rate"]), float(d["cer_p50"]), pct(d["ngram4_f1"]),
                                     pct(d["stub_rate"])))

    wins = sum(1 for ds, _ in DATASETS for t in GRANULARITY_ORDER
               if pct(DEC[(QWEN, ds, t)]["ngram4_f1"]) > rate(QWEN, ds, t))
    show("App. decode / Fig 11", "Qwen3 cells where 4-gram F1 > solve accuracy", "%d of %d" % (wins, 24))

    # Copy-confound counts. residual_status classifies each failed reconstruction; recovery is recomputed
    # here with the current (jiwer) CER rather than read from the stored flag.
    for t, where in (("interleaved_context_word", "App. decode / Fig 11"), ("word_reversal", "App. decode")):
        for ds, tag in DATASETS:
            counts = defaultdict(int)
            for f in glob.glob(os.path.join(EXPERIMENTS, "decode_recovery", "results", QWEN, ds, "*_%s_*.json" % t)):
                for r in json.load(open(f)):
                    if not isinstance(r, dict) or "recovered_text" not in r:
                        continue
                    rec = normalize_for_recovery(r["recovered_text"])
                    orig = normalize_for_recovery(r["canonical_original"])
                    trans = normalize_for_recovery(r["transformed_input"])
                    cer, _ = char_error_rate(orig, rec)
                    recovered = rec == orig or cer <= CER_THRESHOLD
                    counts[residual_status(rec, orig, trans, recovered, bool(r.get("has_recovered_tags")),
                                           CER_THRESHOLD)] += 1
            show(where, "%s %s: copied / closer-to-transformed / total" % (t, tag),
                 "%d / %d / %d" % (counts["copied_transformed_input"],
                                   counts["closer_to_transformed_than_original"], sum(counts.values())))

    both = []
    for m in (N32, N7):
        v = [pct(r["tagged_rate"]) for r in DECODE if r["model"] == m and r["transformation"] in ("opposites", "wrappers")]
        both += v
        show("App. Nemotron", "%s tag rate, Opposites+Wrappers" % SHORT[m], "%.1f .. %.1f" % (min(v), max(v)))
    show("App. Nemotron", "'tag rates are X--Y% on the semantic transformations'", "%.1f .. %.1f" % (min(both), max(both)))
    prompt_engineering_comparison()


# The appendix compares Nemotron-32B's decode run before and after the transformation-rule text was enriched.
# The earlier run was replaced in the working tree, but its result files remain in git history (Git LFS) at
# commit bb53e1b. Both runs are rescored here with the current metric.
EARLIER_RUN = "bb53e1b"


def prompt_engineering_comparison():
    import subprocess
    import decode_recovery_metrics as drm
    repo = os.path.dirname(EXPERIMENTS)
    rel = "experiments/decode_recovery/results/%s/%s/" % (N32, DATASETS[0][0])

    def score(recs):
        recs = [r for r in recs if isinstance(r, dict) and "recovered_text" in r]
        tagged = sum(1 for r in recs if r.get("has_recovered_tags"))
        ok = 0
        for r in recs:
            ref = drm.normalize_ignoring_space(r["canonical_original"])
            hyp = drm.normalize_ignoring_space(r["recovered_text"])
            ok += ref == hyp or char_error_rate(ref, hyp)[0] <= CER_THRESHOLD
        return 100.0 * tagged / len(recs), 100.0 * ok / len(recs)

    try:
        listing = subprocess.run(["git", "ls-tree", "-r", "--name-only", EARLIER_RUN, rel], cwd=repo,
                                 capture_output=True, text=True, check=True).stdout.split()
    except Exception as exc:
        print("  (skipped earlier-run comparison: %s)" % exc)
        return
    for t in ("rail_fence", "rectangle_perimeter"):
        pointer = subprocess.run(["git", "show", "%s:%s" % (EARLIER_RUN, [x for x in listing if "_%s_" % t in x][0])],
                                 cwd=repo, capture_output=True, check=True).stdout
        earlier = json.loads(subprocess.run(["git", "lfs", "smudge"], input=pointer, cwd=repo,
                                            capture_output=True, check=True).stdout)
        current = json.load(open(glob.glob(os.path.join(repo, rel, "*_%s_*.json" % t))[0]))
        (t0, r0), (t1, r1) = score(earlier), score(current)
        show("App. prompt eng.", "Nemotron-32B %s 2024: tag rate earlier -> current" % t, "%.1f -> %.1f" % (t0, t1))
        show("App. prompt eng.", "Nemotron-32B %s 2024: recovery earlier -> current" % t, "%.1f -> %.1f" % (r0, r1))


