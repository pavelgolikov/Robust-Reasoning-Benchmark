# ------------------------------------------------------------------ loading

def read_csv(name):
    with open(os.path.join(STATS, name), newline="") as f:
        return list(csv.DictReader(f))


SUMMARY = read_csv("summary_counts.csv")
PAIRED = read_csv("paired_comparisons.csv")
DECODE = read_csv("decode_recovery_metrics.csv")

RATE = {(r["model"], r["dataset"], r["condition"]): r for r in SUMMARY}
DEC = {(r["model"], r["dataset"], r["transformation"]): r for r in DECODE}
PERTURB = [r for r in PAIRED if r["comparison"] == "perturbation_vs_baseline"]
TRANSFORMS = sorted({r["condition"] for r in PERTURB})


def pct(x):
    return 100.0 * float(x)


def rate(model, dataset, condition):
    return pct(RATE[(model, dataset, condition)]["rate"])


def paired(comparison, model, dataset, condition=None):
    for r in PAIRED:
        if r["comparison"] == comparison and r["model"] == model and r["dataset"] == dataset \
                and (condition is None or r["condition"] == condition):
            return pct(r["problem_mean_difference"]), pct(r["difference_interval_low"]), \
                pct(r["difference_interval_high"])
    raise KeyError((comparison, model, dataset, condition))


def show(where, what, value):
    print("  %-22s %-58s %s" % (where, what, value))


def header(title):
    print("\n" + "=" * 100 + "\n" + title + "\n" + "=" * 100)


# ------------------------------------------------------------------ Section 5.1

def section_5_1():
    header("Section 5.1 and Abstract/Intro -- robustness to perturbations")

    # Figure 4 is drawn by visualize_combined.plot_single_metric from load_metrics_data, which pools every
    # result file of a cell. Its bar value is the mean over the 13 transformations of
    # (baseline accuracy - transformed accuracy), in percentage points. The text quotes the mean of the
    # AIME 2024 and AIME 2025 bars.
    from visualize_combined import load_metrics_data
    data = {tag: load_metrics_data(EXPERIMENTS, ds) for ds, tag in DATASETS}

    def avg_drop(d, model):
        base = d.get("baseline", {}).get(model, {}).get("accuracy")
        if base is None:
            return None
        deltas = [base - d[t][model]["accuracy"] for t in d if t != "baseline" and model in d[t]]
        return sum(deltas) / len(deltas)

    models = sorted(set(data["2024"].get("baseline", {})) | set(data["2025"].get("baseline", {})))
    print("  Figure 4 bars (percentage points) and their two-dataset mean:")
    for m in models:
        a, b = avg_drop(data["2024"], m), avg_drop(data["2025"], m)
        print("      %-40s 2024 %5.1f   2025 %5.1f   mean %5.1f" % (m, a, b, (a + b) / 2))
    show("5.1 / abstract / intro", "GPT-5.4, Gemini, Nemotron-7B, Qwen3, Opus means", "see 'mean' column above")

    ow = [m for m in models if m not in PROPRIETARY]
    worst = []
    for m in ow:
        for tag in ("2024", "2025"):
            d = data[tag]
            base = d["baseline"][m]["accuracy"]
            for t in d:
                if t != "baseline" and m in d[t] and base > 0:
                    worst.append((100.0 * (base - d[t][m]["accuracy"]) / base, m, tag, t))
    w = max(worst)
    show("abstract", "largest RELATIVE drop, open-weights, single cell", "%.1f%%  (%s %s %s)" % w)

    strict = sum(1 for r in PERTURB
                 if float(r["difference_interval_low"]) > 0 or float(r["difference_interval_high"]) < 0)
    show("5.1", "cells whose problem-level interval excludes zero", "%d of %d" % (strict, len(PERTURB)))

    corr = []
    for r in SUMMARY:
        if r["condition"] in TRANSFORMS and r["rate"] and r["accuracy_excluding_cutoffs"]:
            corr.append((pct(r["accuracy_excluding_cutoffs"]) - pct(r["rate"]), r["model"], r["dataset"],
                         r["condition"]))
    show("5.1 / Table 5 caption", "cells where truncation correction < 1 point",
         "%d of %d" % (sum(1 for c in corr if abs(c[0]) < 1.0), len(corr)))
    show("Table 5 caption", "largest truncation correction", "%+.1f  (%s %s %s)" % max(corr))

    worst_char = []
    for m, name in ((QWEN, "Qwen3"), ("DeepSeek-R1-Distill-Llama-70B", "DSR1")):
        key = [k for k in {r["model"] for r in SUMMARY} if m.split("_")[-1] in k][0]
        vals = [(rate(key, ds, t), t, tag) for t in ("interleaved_context_symbol", "rail_fence") for ds, tag in DATASETS]
        worst_char += [v[0] for v in vals]
        show("5.1", "%s accuracy on Interleave (Symbol), Rail Fence" % name,
             "; ".join("%s %s %.1f" % (t, tag, v) for v, t, tag in vals))
    show("5.1", "'Qwen3 and DSR1 drop to at most X% on them'", "X = %.1f" % max(worst_char))

    gem = "gemini-3.1-pro-preview"
    show("5.1", "AIME 2024 Snake (Horizontal) vs (Vertical), Gemini",
         "%.1f vs %.1f" % (rate(gem, DATASETS[0][0], "snake_horizontal"),
                           rate(gem, DATASETS[0][0], "snake_vertical")))
    show("5.1", "AIME 2024 Snake (Horizontal) vs (Vertical), Qwen3",
         "%.1f vs %.1f" % (rate(QWEN, DATASETS[0][0], "snake_horizontal"),
                           rate(QWEN, DATASETS[0][0], "snake_vertical")))

    # Output length (Figure 7 / Appendix "Cognitive Thrashing"): same pooled loader as Figure 7.
    for model, t in ((N7, "rectangle_perimeter"), (QWEN, "snake_vertical")):
        for ds, tag in DATASETS:
            cell = data[tag][t][model]
            show("5.1 / App. thrashing", "%s %s %s: mean output tokens, accuracy" % (SHORT[model], t, tag),
                 "%.0f tokens, %.1f%%" % (cell["length"], cell["accuracy"]))


# ------------------------------------------------------------------ Section 5.2

def section_5_2():
    header("Section 5.2 -- decode-only recovery (Qwen3-30B unless stated)")

    for ds, tag in DATASETS:
        for t in LIKE_FOR_LIKE:
            d = DEC[(QWEN, ds, t)]
            gap = pct(d["recovered_rate"]) - rate(QWEN, ds, t)
            show("5.2 / Fig 5", "%s %s: recovered, solve, gap, stub, median CER" % (t, tag),
                 "%.1f  %.1f  %+.1f  %.1f  %.4f" % (pct(d["recovered_rate"]), rate(QWEN, ds, t), gap,
                                                   pct(d["stub_rate"]), float(d["cer_p50"])))

    for t in ("rail_fence", "snake_vertical"):
        d = DEC[(QWEN, DATASETS[0][0], t)]
        show("5.2", "%s 2024: recovered, stub" % t, "%.1f  %.1f" % (pct(d["recovered_rate"]), pct(d["stub_rate"])))

    stubs = [pct(r["stub_rate"]) for r in DECODE if r["model"] == N7]
    show("5.2", "Nemotron-7B stub rate range over all cells", "%.1f .. %.1f" % (min(stubs), max(stubs)))
    d = DEC[(N7, DATASETS[0][0], "opposites")]
    show("5.2", "Nemotron-7B Opposites 2024: recovered vs solve",
         "%.1f vs %.1f" % (pct(d["recovered_rate"]), rate(N7, DATASETS[0][0], "opposites")))

    # Length of the reference statement. The headline recovery rate (recovered_rate) is scored on the
    # whitespace-stripped text (decode_recovery_metrics.normalize_ignoring_space), so that is the length
    # the 0.02 CER tolerance is applied to.
    import decode_recovery_metrics as drm
    by_ds = defaultdict(dict)
    for ds, tag in DATASETS:
        for f in glob.glob(os.path.join(EXPERIMENTS, "decode_recovery", "results", QWEN, ds, "*_opposites_*.json")):
            for r in json.load(open(f)):
                if isinstance(r, dict) and "canonical_original" in r:
                    by_ds[tag][r["id"]] = r["canonical_original"]
    for label, fn in (("raw", lambda s: s), ("whitespace-stripped (as scored)", drm.normalize_ignoring_space)):
        per = {tag: statistics.median(len(fn(s)) for s in by_ds[tag].values()) for tag in by_ds}
        pooled = statistics.median(len(fn(s)) for tag in by_ds for s in by_ds[tag].values())
        show("5.2 / Fig 11 caption", "median statement length, %s" % label,
             "2024 %.1f   2025 %.1f   pooled %.1f   -> 0.02 x pooled = %.1f chars"
             % (per["2024"], per["2025"], pooled, 0.02 * pooled))
    show("5.2 / Fig 11 caption", "paper quotes: pooled whitespace-stripped median, and 0.02 x it",
         "'255 characters excluding whitespace', 'about 5 characters'")


